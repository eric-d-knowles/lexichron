"""The kernel launcher new-project writes (container/host_kernel.sh): it starts
the Slurm host bridge beside the project's kernel, so notebook code inside the
container can submit jobs. Run with a fake host-python and a fake sbatch."""
import os
import shutil
import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
CONTAINER = ROOT / "container"
if not (CONTAINER / "host_kernel.sh").exists():              # running inside the image
    CONTAINER = Path("/opt/lexichron")
HOST_KERNEL, BRIDGE, NEW_PROJECT = (CONTAINER / n for n in ("host_kernel.sh", "host_bridge.sh", "new_project.sh"))

pytestmark = pytest.mark.skipif(shutil.which("bash") is None or shutil.which("python3") is None,
                                reason="needs bash and python3")

# Stands in for host-python: asks the bridge to run sbatch, as lexichron.bridge
# does from inside the container, and prints the answer.
FAKE_PYTHON = r"""#!/usr/bin/env bash
echo "args: $*"
echo "bridge: ${LEXICHRON_BRIDGE_DIR:-none}"
[ -n "${LEXICHRON_BRIDGE_DIR:-}" ] || exit 0
# lexichron.bridge.HostBridge.available: the bridge has written its pid
for i in $(seq 100); do [ -e "$LEXICHRON_BRIDGE_DIR/bridge.pid" ] && [ -d "$LEXICHRON_BRIDGE_DIR/req" ] && break; sleep 0.1; done
echo '{"cmd": "sbatch", "args": ["job.sbatch"]}' > "$LEXICHRON_BRIDGE_DIR/req/r1.json.tmp"
mv "$LEXICHRON_BRIDGE_DIR/req/r1.json.tmp" "$LEXICHRON_BRIDGE_DIR/req/r1.json"
for i in $(seq 100); do [ -e "$LEXICHRON_BRIDGE_DIR/res/r1.json" ] && break; sleep 0.1; done
cat "$LEXICHRON_BRIDGE_DIR/res/r1.json"
"""


@pytest.fixture
def project(tmp_path):
    proj = tmp_path / "proj"
    (proj / ".venv").mkdir(parents=True)
    (proj / ".lexichron").mkdir()
    shutil.copy(HOST_KERNEL, proj / ".venv" / "host-kernel")
    shutil.copy(BRIDGE, proj / ".lexichron" / "host_bridge.sh")
    (proj / ".lexichron" / "host_bridge.sh").chmod(0o755)
    (proj / ".venv" / "host-python").write_text(FAKE_PYTHON)
    for p in (proj / ".venv" / "host-kernel", proj / ".venv" / "host-python"):
        p.chmod(0o755)
    fake_bin = tmp_path / "fakebin"
    fake_bin.mkdir()
    (fake_bin / "sbatch").write_text('#!/usr/bin/env bash\necho "Submitted batch job 42 ($*)"\n')
    (fake_bin / "sbatch").chmod(0o755)
    keep = [d for d in os.environ["PATH"].split(os.pathsep) if d and not (Path(d) / "sbatch").exists()]
    env = {k: v for k, v in os.environ.items() if k not in ("BASH_ENV", "ENV", "LEXICHRON_BRIDGE_DIR")}
    return proj, fake_bin, keep, env


def _run(proj, path, env):
    return subprocess.run([str(proj / ".venv" / "host-kernel"), "-m", "ipykernel_launcher", "-f", "c.json"],
                          env=dict(env, PATH=os.pathsep.join(path)), capture_output=True, text=True, timeout=60)


def test_the_kernel_gets_a_bridge_that_runs_sbatch_on_the_host(project):
    proj, fake_bin, keep, env = project
    out = _run(proj, [str(fake_bin)] + keep, env)
    assert out.returncode == 0, out.stderr
    assert "args: -m ipykernel_launcher -f c.json" in out.stdout            # arguments pass through
    assert f"bridge: {proj}/.lexichron/bridge-kernel-" in out.stdout
    assert '"rc": 0' in out.stdout and "Submitted batch job 42 (job.sbatch)" in out.stdout


def test_without_slurm_the_kernel_starts_without_a_bridge(project):
    proj, _, keep, env = project
    out = _run(proj, keep, env)
    assert out.returncode == 0, out.stderr
    assert "bridge: none" in out.stdout
    assert not list((proj / ".lexichron").glob("bridge-kernel-*"))


def test_bridge_directories_of_finished_kernels_are_removed(project):
    proj, fake_bin, keep, env = project
    host = subprocess.run(["hostname", "-s"], capture_output=True, text=True).stdout.strip()
    stale = proj / ".lexichron" / f"bridge-kernel-{host}-999999999"
    stale.mkdir()
    assert _run(proj, [str(fake_bin)] + keep, env).returncode == 0
    assert not stale.exists()


def test_new_project_points_the_kernel_at_host_kernel_and_keeps_a_users_own():
    text = NEW_PROJECT.read_text()
    assert '--kernel-command "$KERNEL_SH"' in text
    assert "cp /opt/lexichron/host_bridge.sh" in text                       # refreshed on every run
    # the marker new-project looks for is the one the generated file carries
    assert 'grep -q "Generated by lexichron new-project"' in text
    assert "Generated by lexichron new-project" in HOST_KERNEL.read_text()
